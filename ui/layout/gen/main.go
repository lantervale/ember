//go:build chrome

// Command gen writes package layout's tables of the line breaks Chrome
// takes between two printable ASCII characters, under word-break: normal
// and break-all, read from headless Chrome itself: each pair in a box of
// no width, a break where its two characters fall on two lines.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"strings"

	"github.com/lantervale/ember/geom"
	"github.com/lantervale/ember/ui"
	"github.com/lantervale/ember/ui/internal/chrome"
)

const first, last = '!', '~'

const measure = `
const first = 0x21, last = 0x7E, n = last - first + 1;
const table = wordBreak => {
	const root = document.createElement("div");
	root.style.wordBreak = wordBreak;
	const nodes = [];
	for (let a = first; a <= last; a++) {
		for (let b = first; b <= last; b++) {
			const d = document.createElement("div");
			d.style.cssText = "display: inline-block; width: 0; vertical-align: top; margin-right: 40px;";
			const t = document.createTextNode(String.fromCharCode(a, b));
			d.appendChild(t);
			root.appendChild(d);
			nodes.push(t);
		}
	}
	document.body.appendChild(root);
	const r = document.createRange();
	const top = (t, i) => (r.setStart(t, i), r.setEnd(t, i + 1), r.getBoundingClientRect().top);
	const rows = [];
	for (let a = 0; a < n; a++) {
		let row = "";
		for (let b = 0; b < n; b++) row += top(nodes[a * n + b], 1) > top(nodes[a * n + b], 0) ? "1" : "0";
		rows.push(row);
	}
	root.remove();
	return rows;
};
return {agent: navigator.userAgent.match(/Chrome\/[\d.]+/)[0], normal: table("normal"), breakAll: table("break-all")};
`

func main() {
	out := flag.String("out", "asciibreaks_gen.go", "the Go file to write")
	flag.Parse()
	data, err := chrome.Eval(ui.NewDocument(), geom.V2(800, 600), measure)
	if err != nil {
		log.Fatal(err)
	}
	var res struct {
		Agent    string   `json:"agent"`
		Normal   []string `json:"normal"`
		BreakAll []string `json:"breakAll"`
	}
	if err = json.Unmarshal(data, &res); err != nil {
		log.Fatal(err)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by gen from %s; DO NOT EDIT.\n\npackage layout\n\n", res.Agent)
	fmt.Fprintf(&b, "const asciiCount = %d\n", last-first+1)
	write(&b, "asciiBreaks", "", res.Normal)
	write(&b, "asciiBreaksAll", " under word-break: break-all", res.BreakAll)
	//nolint:gosec // a source file git tracks, readable by all
	if err = os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
}

// write writes the table named name to b, a row per first character and
// a bit per second.
func write(b *strings.Builder, name, under string, rows []string) {
	if len(rows) != last-first+1 {
		log.Fatalf("%d rows from Chrome", len(rows))
	}
	fmt.Fprintf(b, "\n// %s[a-'!'] has bit b-'!' set where Chrome may break a line between\n", name)
	fmt.Fprintf(b, "// the printable ASCII characters a and b%s.\n", under)
	fmt.Fprintf(b, "var %s = [asciiCount][2]uint64{\n", name)
	for i, row := range rows {
		var bits [2]uint64
		for k, c := range row {
			if c == '1' {
				bits[k/64] |= 1 << (k % 64)
			}
		}
		fmt.Fprintf(b, "\t{0x%016X, 0x%016X}, // %c\n", bits[0], bits[1], first+i)
	}
	b.WriteString("}\n")
}
