// Command gen writes the table of package orient from the Unicode
// Character Database's VerticalOrientation.txt (UAX #50): each range of
// characters not drawn turned, and how it is drawn.
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"io"
	"log"
	"net/http"
	"os"
	"strconv"
	"strings"
)

func main() {
	src := flag.String("src", "", "the UCD's VerticalOrientation.txt, a URL or a file")
	out := flag.String("out", "orient_gen.go", "the Go file to write")
	flag.Parse()
	data, err := read(*src)
	if err != nil {
		log.Fatal(err)
	}
	values := map[string]string{"R": "", "U": "Upright", "Tu": "TransformedUpright", "Tr": "TransformedRotated"}
	vo := make([]string, 0x110000)
	name := ""
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		line := sc.Text()
		if name == "" {
			name = strings.TrimSpace(strings.TrimPrefix(line, "#"))
			name, _, _ = strings.Cut(name, ",")
		}
		// a @missing line sets the value of the code points the lines after it leave out
		line = strings.TrimPrefix(line, "# @missing:")
		line, _, _ = strings.Cut(line, "#")
		field, value, ok := strings.Cut(line, ";")
		if !ok {
			continue
		}
		v, known := values[strings.TrimSpace(value)]
		if !known {
			log.Fatalf("unknown orientation %q", value)
		}
		lo, hi, _ := strings.Cut(strings.TrimSpace(field), "..")
		if hi == "" {
			hi = lo
		}
		first, err := strconv.ParseUint(lo, 16, 32)
		if err != nil {
			log.Fatal(err)
		}
		last, err := strconv.ParseUint(hi, 16, 32)
		if err != nil {
			log.Fatal(err)
		}
		for r := first; r <= last; r++ {
			vo[r] = v
		}
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by gen from %s; DO NOT EDIT.\n\npackage orient\n\nvar ranges = [...]span{\n", name)
	for r := 0; r < len(vo); {
		end := r
		for end+1 < len(vo) && vo[end+1] == vo[r] {
			end++
		}
		if vo[r] != "" {
			fmt.Fprintf(&b, "\t{0x%04X, 0x%04X, %s},\n", r, end, vo[r])
		}
		r = end + 1
	}
	b.WriteString("}\n")
	//nolint:gosec // a source file git tracks, readable by all
	if err = os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
}

func read(src string) ([]byte, error) {
	if !strings.HasPrefix(src, "http") {
		return os.ReadFile(src)
	}
	resp, err := http.Get(src) //nolint:gosec,noctx // the table's source, a flag of a one-off generator
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: %s", src, resp.Status)
	}
	return io.ReadAll(resp.Body)
}
