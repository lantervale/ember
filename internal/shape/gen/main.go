// vowelTable is HarfBuzz's gen-vowel-constraints.py: the sequences of
// characters a dotted circle goes into, before their last.
func vowelTable(data []byte) string {
	var seqs [][]rune
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		line, _, _ := strings.Cut(sc.Text(), "#")
		line, _, _ = strings.Cut(line, ";")
		var seq []rune
		for f := range strings.FieldsSeq(line) {
			r, err := strconv.ParseUint(f, 16, 21)
			if err != nil {
				log.Fatal(err)
			}
			seq = append(seq, rune(r))
		}
		if len(seq) >= 2 {
			seqs = append(seqs, seq)
		}
	}
	sort.SliceStable(seqs, func(i, j int) bool { return slices.Compare(seqs[i], seqs[j]) < 0 })
	var b strings.Builder
	b.WriteString("var vowelConstraints = [...][]rune{\n")
	for _, s := range seqs {
		parts := make([]string, len(s))
		for i, r := range s {
			parts[i] = fmt.Sprintf("0x%04X", r)
		}
		fmt.Fprintf(&b, "\t{%s},\n", strings.Join(parts, ", "))
	}
	b.WriteString("}\n")
	return b.String()
}
