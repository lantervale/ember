// Command gen writes the joining table of package shape from Unicode's
// ArabicShaping.txt: each character's joining type, Syriac's Alaph and
// Dalath Rish groups apart, in ranges.
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"io"
	"log"
	"net/http"
	"os"
	"sort"
	"strconv"
	"strings"
)

func main() {
	src := flag.String("src", "", "ArabicShaping.txt, a URL or a file")
	out := flag.String("out", "joining_gen.go", "the Go file to write")
	flag.Parse()
	data, err := read(*src)
	if err != nil {
		log.Fatal(err)
	}
	kinds := map[string]string{
		"U": "joinU", "L": "joinL", "R": "joinR", "D": "joinD", "C": "joinC", "T": "joinT",
	}
	type entry struct {
		r    rune
		kind string
	}
	var entries []entry
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		line, _, _ := strings.Cut(sc.Text(), "#")
		fields := strings.Split(line, ";")
		if len(fields) < 4 {
			continue
		}
		code, perr := strconv.ParseUint(strings.TrimSpace(fields[0]), 16, 21)
		if perr != nil {
			log.Fatal(perr)
		}
		kind, ok := kinds[strings.TrimSpace(fields[2])]
		if !ok {
			log.Fatalf("%s: no joining type %q", fields[0], fields[2])
		}
		switch strings.TrimSpace(fields[3]) {
		case "ALAPH":
			kind = "joinAlaph"
		case "DALATH RISH":
			kind = "joinDalathRish"
		}
		entries = append(entries, entry{rune(code), kind})
	}
	if err = sc.Err(); err != nil {
		log.Fatal(err)
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].r < entries[j].r })
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by gen from %s; DO NOT EDIT.\n\npackage shape\n\n", *src)
	b.WriteString("var joinings = [...]joiningRange{\n")
	for i := 0; i < len(entries); {
		j := i
		for j+1 < len(entries) && entries[j+1].kind == entries[i].kind && entries[j+1].r == entries[j].r+1 {
			j++
		}
		fmt.Fprintf(&b, "\t{0x%04X, 0x%04X, %s},\n", entries[i].r, entries[j].r, entries[i].kind)
		i = j + 1
	}
	b.WriteString("}\n")
	//nolint:gosec // a source file git tracks, readable by all
	if err = os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
}

func read(src string) ([]byte, error) {
	if !strings.HasPrefix(src, "http") {
		return os.ReadFile(src)
	}
	resp, err := http.Get(src) //nolint:gosec,noctx // the table's source, the -src flag of a one-off generator
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: %s", src, resp.Status)
	}
	return io.ReadAll(resp.Body)
}
