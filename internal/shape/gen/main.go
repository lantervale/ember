// Command gen writes the character tables of package shape from
// Unicode's character database and HarfBuzz's additions to it for the
// Universal Shaping Engine (its ms-use folder): the joining types of
// ArabicShaping.txt, the categories and positions HarfBuzz's Indic,
// Khmer and Myanmar shapers read (gen-indic-table.py), the categories
// of the Universal Shaping Engine (gen-use-table.py), and the vowel
// sequences that take a dotted circle (gen-vowel-constraints.py).
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"io"
	"log"
	"net/http"
	"os"
	"slices"
	"sort"
	"strconv"
	"strings"
)

func main() {
	ucd := flag.String("ucd", "", "the folder of Unicode's character database, a URL or a directory")
	msuse := flag.String("msuse", "", "HarfBuzz's ms-use folder, a URL or a directory")
	flag.Parse()
	in := func(dir, name string) []byte {
		data, err := read(dir + "/" + name)
		if err != nil {
			log.Fatal(err)
		}
		return data
	}
	files := map[string][]byte{}
	for _, name := range []string{"ArabicShaping.txt", "IndicSyllabicCategory.txt", "IndicPositionalCategory.txt",
		"Blocks.txt", "DerivedCoreProperties.txt", "UnicodeData.txt", "Scripts.txt"} {
		files[name] = in(*ucd, name)
	}
	for _, name := range []string{"IndicSyllabicCategory-Additional.txt", "IndicPositionalCategory-Additional.txt",
		"IndicShapingInvalidCluster.txt"} {
		files[name] = in(*msuse, name)
	}
	source := fmt.Sprintf("%s and %s", *ucd, *msuse)
	write("joining_gen.go", source, joiningTable(files["ArabicShaping.txt"]))
	write("indic_gen.go", source, indicTable(files))
	write("use_gen.go", source, useTable(files))
	write("vowels_gen.go", source, vowelTable(files["IndicShapingInvalidCluster.txt"]))
}

func write(name, source, body string) {
	text := fmt.Sprintf("// Code generated by gen from %s; DO NOT EDIT.\n\npackage shape\n\n%s", source, body)
	//nolint:gosec // a source file git tracks, readable by all
	if err := os.WriteFile(name, []byte(text), 0o644); err != nil {
		log.Fatal(err)
	}
}

func read(src string) ([]byte, error) {
	if !strings.HasPrefix(src, "http") {
		return os.ReadFile(src)
	}
	resp, err := http.Get(src) //nolint:gosec,noctx // the table's source, a flag of a one-off generator
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: %s", src, resp.Status)
	}
	return io.ReadAll(resp.Body)
}

// records calls fn with each range of a UCD file and its field-th
// field, comments left out.
func records(data []byte, field int, fn func(lo, hi rune, value string)) {
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		line, _, _ := strings.Cut(sc.Text(), "#")
		fields := strings.Split(line, ";")
		if len(fields) <= field {
			continue
		}
		code := strings.TrimSpace(fields[0])
		first, last, ranged := strings.Cut(code, "..")
		lo, err := strconv.ParseUint(first, 16, 21)
		if err != nil {
			log.Fatalf("%q: %v", line, err)
		}
		hi := lo
		if ranged {
			if hi, err = strconv.ParseUint(last, 16, 21); err != nil {
				log.Fatalf("%q: %v", line, err)
			}
		}
		fn(rune(lo), rune(hi), strings.TrimSpace(fields[field]))
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
}

// property reads field of a UCD file into a map.
func property(data []byte, field int) map[rune]string {
	out := map[rune]string{}
	records(data, field, func(lo, hi rune, v string) {
		for r := lo; r <= hi; r++ {
			out[r] = v
		}
	})
	return out
}

// ranges writes values, by character, as ranges of equal values, named
// name of type typ, each value written by format.
func ranges[V comparable](name, typ string, values map[rune]V, format func(V) string) string {
	keys := make([]rune, 0, len(values))
	for r := range values {
		keys = append(keys, r)
	}
	slices.Sort(keys)
	var b strings.Builder
	fmt.Fprintf(&b, "var %s = [...]%s{\n", name, typ)
	for i := 0; i < len(keys); {
		j := i
		for j+1 < len(keys) && keys[j+1] == keys[j]+1 && values[keys[j+1]] == values[keys[i]] {
			j++
		}
		fmt.Fprintf(&b, "\t{0x%04X, 0x%04X, %s},\n", keys[i], keys[j], format(values[keys[i]]))
		i = j + 1
	}
	b.WriteString("}\n")
	return b.String()
}

func joiningTable(data []byte) string {
	kinds := map[string]string{
		"U": "joinU", "L": "joinL", "R": "joinR", "D": "joinD", "C": "joinC", "T": "joinT",
	}
	values := map[rune]string{}
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		line, _, _ := strings.Cut(sc.Text(), "#")
		fields := strings.Split(line, ";")
		if len(fields) < 4 {
			continue
		}
		code, err := strconv.ParseUint(strings.TrimSpace(fields[0]), 16, 21)
		if err != nil {
			log.Fatal(err)
		}
		kind, ok := kinds[strings.TrimSpace(fields[2])]
		if !ok {
			log.Fatalf("%s: no joining type %q", fields[0], fields[2])
		}
		switch strings.TrimSpace(fields[3]) {
		case "ALAPH":
			kind = "joinAlaph"
		case "DALATH RISH":
			kind = "joinDalathRish"
		}
		values[rune(code)] = kind
	}
	return ranges("joinings", "joiningRange", values, func(s string) string { return s })
}

// indicTable is HarfBuzz's gen-indic-table.py: the category and the
// position of each character of the blocks its Indic, Khmer and
// Myanmar shapers read.
//
//nolint:funlen,goconst // gen-indic-table.py's steps over Unicode's values
func indicTable(files map[string][]byte) string {
	isc := property(files["IndicSyllabicCategory.txt"], 1)
	ipc := property(files["IndicPositionalCategory.txt"], 1)
	blocks := property(files["Blocks.txt"], 1)
	allowed := []string{"Basic Latin", "Latin-1 Supplement", "Devanagari", "Bengali", "Gurmukhi", "Gujarati", "Oriya",
		"Tamil", "Telugu", "Kannada", "Malayalam", "Myanmar", "Khmer", "Vedic Extensions", "General Punctuation",
		"Superscripts and Subscripts", "Devanagari Extended", "Myanmar Extended-B", "Myanmar Extended-A",
		"Myanmar Extended-C", "Devanagari Extended-A", "Bengali Supplement"}
	type entry struct{ cat, pos, block string }
	data := map[rune]entry{}
	for r := range isc {
		data[r] = entry{isc[r], "Not_Applicable", blocks[r]}
	}
	for r, p := range ipc {
		e, ok := data[r]
		if !ok {
			e = entry{"Other", "", blocks[r]}
		}
		e.pos = p
		data[r] = e
	}
	for r, e := range data {
		if r != 0x00A0 && r != 0x25CC && !slices.Contains(allowed, e.block) {
			delete(data, r)
		}
	}
	categories := map[string]string{
		"Other": "X", "Avagraha": "Symbol", "Bindu": "SM", "Brahmi_Joining_Number": "PLACEHOLDER",
		"Cantillation_Mark": "A", "Consonant": "C", "Consonant_Dead": "C", "Consonant_Final": "CM",
		"Consonant_Head_Letter": "C", "Consonant_Initial_Postfixed": "C", "Consonant_Killer": "M",
		"Consonant_Medial": "CM", "Consonant_Placeholder": "PLACEHOLDER", "Consonant_Preceding_Repha": "Repha",
		"Consonant_Prefixed": "X", "Consonant_Subjoined": "CM", "Consonant_Succeeding_Repha": "CM",
		"Consonant_With_Stacker": "CS", "Gemination_Mark": "SM", "Invisible_Stacker": "H", "Joiner": "ZWJ",
		"Modifying_Letter": "X", "Non_Joiner": "ZWNJ", "Nukta": "N", "Number": "PLACEHOLDER",
		"Number_Joiner": "PLACEHOLDER", "Pure_Killer": "M", "Register_Shifter": "RS", "Syllable_Modifier": "SM",
		"Tone_Letter": "X", "Tone_Mark": "N", "Virama": "H", "Visarga": "SM", "Vowel": "V", "Vowel_Dependent": "M",
		"Vowel_Independent": "V",
	}
	positions := map[string]string{
		"Not_Applicable": "End", "Left": "PreC", "Top": "AboveC", "Bottom": "BelowC", "Right": "PostC",
		"Bottom_And_Right": "PostC", "Left_And_Right": "PostC", "Top_And_Bottom": "BelowC",
		"Top_And_Bottom_And_Left": "BelowC", "Top_And_Bottom_And_Right": "PostC", "Top_And_Left": "AboveC",
		"Top_And_Left_And_Right": "PostC", "Top_And_Right": "PostC", "Overstruck": "AfterMain",
		"Visual_order_left": "PreM",
	}
	out := map[rune]entry{}
	for r, e := range data {
		cat, ok := categories[e.cat]
		if !ok {
			log.Fatalf("U+%04X: no Indic category for %q", r, e.cat)
		}
		if cat == "SM" && e.pos == "Not_Applicable" {
			cat = "SMPst"
		}
		pos, ok := positions[e.pos]
		if !ok {
			log.Fatalf("U+%04X: no Indic position for %q", r, e.pos)
		}
		out[r] = entry{cat, pos, e.block}
	}
	for r, cat := range indicCategoryOverrides() {
		e, ok := out[r]
		if !ok {
			e.pos = "End"
		}
		e.cat, e.block = cat, blocks[r]
		out[r] = e
	}
	for r, e := range out {
		if !slices.Contains([]string{"CM", "SM", "RS", "H", "M", "MPst"}, e.cat) {
			e.pos = "End"
		}
		switch {
		case slices.Contains([]string{"C", "CS", "Ra", "CM", "V", "PLACEHOLDER", "DOTTEDCIRCLE"}, e.cat):
			e.pos = "BaseC"
		case e.cat == "M" || e.cat == "MPst":
			if strings.HasPrefix(e.block, "Khmer") || strings.HasPrefix(e.block, "Myanmar") {
				e.cat = map[string]string{"PreC": "VPre", "AboveC": "VAbv", "BelowC": "VBlw", "PostC": "VPst"}[e.pos]
				if e.cat == "" {
					log.Fatalf("U+%04X: a vowel of no position", r)
				}
			} else {
				e.pos = matraPosition(r, e.pos, e.block)
			}
		case slices.Contains([]string{"SM", "SMPst", "VD", "A", "Symbol"}, e.cat):
			e.pos = "SMVD"
		}
		out[r] = e
	}
	out[0x0A51] = entry{out[0x0A51].cat, "BelowC", blocks[0x0A51]}
	out[0x0B01] = entry{out[0x0B01].cat, "BeforeSub", blocks[0x0B01]}
	values := map[rune]string{}
	for r, e := range out {
		values[r] = "i" + e.cat + ", pos" + e.pos
	}
	return ranges("indicCategories", "indicRange", values, func(s string) string { return s })
}

